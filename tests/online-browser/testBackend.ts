async function startFixtureDatabase() {
  const databaseUrl = process.env.ONLINE_E2E_DATABASE_URL;
  if (databaseUrl) {
    const url = new URL(databaseUrl);
    if (url.hostname !== '127.0.0.1' || url.pathname !== '/drag_online_test') throw new Error('Use o PostgreSQL local descartável drag_online_test.');
    const sql = postgres(databaseUrl, { max: 1 });
    try {
      await sql.unsafe(authSchema).simple();
      await sql.unsafe(migration).simple();
      await sql`insert into auth.users values (${accounts[0]}), (${accounts[1]}), (${accounts[2]})`;
    } finally { await sql.end(); }
    return { url: databaseUrl, poolSize: 12, close: undefined, fundWorkshop: async () => {
      const local = postgres(databaseUrl, { max: 1 });
      try {
        await local`update online_wallets set cr_balance = 20000 where user_id = ${accounts[2]!}`;
        await local`update online_car_progression set pp_balance = 500, pp_earned_total = 500
          where car_id in (select id from online_cars where user_id = ${accounts[2]!})`;
      } finally { await local.end(); }
    } };
  }

  const db = await PGlite.create();
  await db.exec(authSchema);
  await db.exec(migration);
  await db.query('insert into auth.users values ($1), ($2), ($3)', accounts);
  const socket = new PGLiteSocketServer({ db, port: 0, maxConnections: 1 });
  await socket.start();
  return { url: `postgresql://postgres@${socket.getServerConn()}/postgres`, poolSize: 1,
    fundWorkshop: async () => {
      await db.query('update online_wallets set cr_balance = 20000 where user_id = $1', [accounts[2]]);
      await db.query('update online_car_progression set pp_balance = 500, pp_earned_total = 500 where car_id in (select id from online_cars where user_id = $1)', [accounts[2]]);
    },
    close: async () => { await socket.stop(); await db.close(); } };
}

const database = await startFixtureDatabase();

const encode = (value: unknown) => Buffer.from(JSON.stringify(value)).toString('base64url');
function session(id: string) {
  const now = Math.floor(Date.now() / 1000);
  const user = { id, aud: 'authenticated', role: 'authenticated', app_metadata: { provider: 'google' }, user_metadata: {},
    created_at: new Date().toISOString() };
  const expires = now + 3_600;
  const data = `${encode({ alg: 'ES256', typ: 'JWT', kid: keyId })}.${encode({
    sub: id, iss: `${auth}/auth/v1`, aud: user.aud, role: user.role, app_metadata: user.app_metadata,
    exp: expires, iat: now, session_id: randomUUID(),
  })}`;
  const signature = sign('sha256', Buffer.from(data), { key: privateKey, dsaEncoding: 'ieee-p1363' }).toString('base64url');
  return { access_token: `${data}.${signature}`, refresh_token: randomUUID(), token_type: 'bearer', expires_in: 3_600, expires_at: expires, user };
}

// Test-only OAuth provider on loopback. It enforces the actual code verifier generated by supabase-js.
const provider = createServer(async (request, response) => {
  response.setHeader('Access-Control-Allow-Origin', ui);
  response.setHeader('Access-Control-Allow-Headers', 'authorization, apikey, content-type, x-client-info, x-supabase-api-version');
  response.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
  response.setHeader('Content-Type', 'application/json');
  if (request.method === 'OPTIONS') { response.writeHead(204).end(); return; }
  const url = new URL(request.url ?? '/', auth);
  if (url.pathname === '/fixture/workshop' && request.method === 'POST') {
    await database.fundWorkshop();
    response.writeHead(204).end();
  } else if (url.pathname === '/auth/v1/.well-known/jwks.json') {
    response.end(JSON.stringify({ keys: [{ ...publicKey.export({ format: 'jwk' }), kid: keyId, alg: 'ES256', use: 'sig', key_ops: ['verify'] }] }));
  } else if (url.pathname === '/auth/v1/authorize') {
    const id = accounts[Number(request.headers['x-fixture-account'])];
    const challenge = url.searchParams.get('code_challenge');
    const redirect = url.searchParams.get('redirect_to');
    if (!id || !challenge || redirect !== `${ui}/auth/callback` || url.searchParams.get('provider') !== 'google') {
      response.writeHead(400).end('{}'); return;
    }
    const code = randomUUID();
    codes.set(code, { id, challenge });
    response.writeHead(302, { Location: `${redirect}?code=${code}` }).end();
  } else if (url.pathname === '/auth/v1/token' && url.searchParams.get('grant_type') === 'pkce') {
    try {
      const chunks: Buffer[] = [];
      for await (const chunk of request) chunks.push(chunk as Buffer);
      const body = JSON.parse(Buffer.concat(chunks).toString()) as { auth_code: string; code_verifier: string };
      const grant = codes.get(body.auth_code);
      if (!grant || createHash('sha256').update(body.code_verifier).digest('base64url') !== grant.challenge) {
        response.writeHead(400).end('{}'); return;
      }
      codes.delete(body.auth_code);
      response.end(JSON.stringify(session(grant.id)));
    } catch { response.writeHead(400).end('{}'); }
  } else if (url.pathname === '/auth/v1/logout') {
    response.writeHead(204).end();
  } else {
    response.writeHead(404).end('{}');
  }
});

await new Promise<void>((resolve) => provider.listen(54751, '127.0.0.1', resolve));
