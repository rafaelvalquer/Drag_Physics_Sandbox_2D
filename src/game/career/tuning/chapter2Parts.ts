import type { PartDef } from './parts';

/**
 * Chapter 2 workshop ("Liga da Madrugada"): parts known only by BuildResolver v2.
 *
 * Every part is hardware with a physical effect (boost target, charge temperature, compressor
 * flow, valve events, compression, mechanical limits, inertia, clutch capacity, load transfer).
 * None of them scales power: the new torque curve always comes out of the engine model.
 *
 * Compatibility is explicit: engine family, induction, gearbox kind and driven axle. A part of
 * the K20 never fits a N55, a manual clutch never fits a DSG, the AWD calibration only fits AWD.
 */

/** Mechanical and calibration data of each engine family (estimated: tuner literature). */
export interface EngineFamilyDef {
  id: string;
  label: string;
  induction: 'NA' | 'turbo';
  /** Brake torque the factory pistons/rods take with a sane margin (N·m). */
  internalsTorqueNm: number;
  /** Boost the family runs on 98 RON without ignition retard (bar); turbo families only. */
  knockFreeBoostBar?: number;
  /** Rev-limit raise the factory valve train accepts (rpm). */
  valvetrainRevAddRpm: number;
  /**
   * Compressor headroom relative to the rated point of this version (1 = the usual 12 %). Larger
   * on software-detuned versions that share the turbo of a stronger one (N20 184 hp / 245 hp,
   * M274 184 cv / 245 cv).
   */
  compressorMarginScale?: number;
}

